"""Microcontroller side of the project: firmware parameters, the serial protocol, and a PC test rig.

The ESP32 firmware in ``firmware/hushwave_esp32`` is a single-precision port of the frozen B5
engine. This module

* writes ``hushwave_params.h`` from ``results/tuning.json`` and the Python engine, so that the
  firmware constants are never typed by hand (``make firmware-params``),
* implements the frame protocol that the browser and the board speak (the browser version is
  ``demo/web/protocol.js``; both follow the specification in ``docs/PROTOCOL.md``),
* builds the same C++ sources for the PC and runs them behind a pipe (``HostDevice``), which is how
  the tests compare the firmware with the Python reference sample by sample.
"""

from __future__ import annotations

import json
import shutil
import struct
import subprocess
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path
from types import TracebackType

import numpy as np
from numpy.typing import ArrayLike, NDArray

from hushwave.live import ROOT, TUNING_PATH, load_b5
from hushwave.noise_est import McraEstimator, RiseLimitedEstimator, make_estimator
from hushwave.systems import resolve

FloatArray = NDArray[np.float64]
FIRMWARE_DIR = ROOT / "firmware" / "hushwave_esp32"
HOST_DIR = ROOT / "firmware" / "host"
PARAMS_PATH = FIRMWARE_DIR / "hushwave_params.h"
SOURCES = ("hushwave_core.cpp", "hushwave_protocol.cpp")

SYNC = b"\xa5\x5a"
TYPE_AUDIO_IN, TYPE_AUDIO_OUT = 0x01, 0x81
TYPE_HELLO, TYPE_HELLO_REPLY = 0x02, 0x82
TYPE_RESET, TYPE_RESET_ACK = 0x03, 0x83
PROTOCOL_VERSION = 1
BLOCK = 256
MAX_PAYLOAD = 1024
PCM_SCALE = 32768.0


# ------------------------------------------------------------------ parameters
def _f(value: float) -> str:
    return f"{value:.9g}f" if "e" in f"{value:.9g}" or "." in f"{value:.9g}" else f"{value:.9g}.0f"


def firmware_params(tuning_path: Path = TUNING_PATH) -> str:
    """Text of hushwave_params.h for the frozen B5 system."""
    system = load_b5(tuning_path)
    if (system.rule, system.estimator, system.prefilter) != ("wiener", "mcra", "spectral"):
        raise ValueError("the firmware implements Wiener, MCRA and the spectral high-pass only")
    cfg, gain, est = resolve(system)
    tracker = make_estimator(system.estimator, cfg.n_bins, cfg, **est)
    if not isinstance(tracker, RiseLimitedEstimator) or not isinstance(
        tracker.inner, McraEstimator
    ):
        raise ValueError("the firmware needs MCRA with a rise limit")
    mcra = tracker.inner
    if (cfg.fs, cfg.frame_len, cfg.hop) != (16_000, 512, 256):
        raise ValueError("the firmware is built for 16 kHz, 512-sample frames and a 256-sample hop")
    if gain.get("gain_mu", cfg.gain_mu) != 0.0 or gain.get("spectral_hp", 0.0) < 0.5:
        raise ValueError("the firmware needs no gain smoothing and the spectral high-pass")
    lines = [
        "// Generated by scripts/gen_firmware_params.py from results/tuning.json. Do not edit.",
        "#pragma once",
        "",
        "namespace hushwave {",
        f"constexpr float kHpCutoffHz = {_f(cfg.hp_cutoff_hz)};",
        f"constexpr float kMcraAlphaS = {_f(mcra.alpha_s)};",
        f"constexpr float kMcraAlphaP = {_f(mcra.alpha_p)};",
        f"constexpr float kMcraAlphaD = {_f(mcra.alpha_d)};",
        f"constexpr float kMcraDelta = {_f(mcra.delta)};",
        f"constexpr float kMcraBias = {_f(mcra.bias)};",
        f"constexpr int kMcraWarmupFrames = {mcra._warmup};",
        f"constexpr int kMinSubWindows = {mcra._min.n_sub};",
        f"constexpr int kMinSubFrames = {mcra._min.sub_frames};",
        f"constexpr float kNoiseFloor = {_f(mcra.floor)};",
        f"constexpr float kRiseRatio = {_f(tracker.ratio)};",
        f"constexpr float kDdAlpha = {_f(gain.get('dd_alpha', cfg.dd_alpha))};",
        f"constexpr float kGainFloor = {_f(gain.get('g_min', cfg.g_min))};",
        "}  // namespace hushwave",
        "",
    ]
    return "\n".join(lines)


def write_params(path: Path = PARAMS_PATH, tuning_path: Path = TUNING_PATH) -> Path:
    path.write_text(firmware_params(tuning_path), encoding="utf-8")
    return path


# -------------------------------------------------------------------- protocol
def crc16(data: bytes) -> int:
    """CRC-16/CCITT-FALSE: polynomial 0x1021, initial value 0xFFFF, no reflection."""
    crc = 0xFFFF
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def encode_frame(kind: int, seq: int, payload: bytes = b"") -> bytes:
    if not 0 <= kind <= 0xFF or not 0 <= seq <= 0xFF:
        raise ValueError("kind and seq must fit in one byte")
    if len(payload) > MAX_PAYLOAD:
        raise ValueError(f"payload longer than {MAX_PAYLOAD} bytes")
    body = struct.pack("<BBH", kind, seq, len(payload)) + payload
    return SYNC + body + struct.pack("<H", crc16(body))


@dataclass(frozen=True)
class Frame:
    kind: int
    seq: int
    payload: bytes


class FrameParser:
    """Byte-stream parser: sync marker, length and CRC checks, and resynchronisation."""

    def __init__(self) -> None:
        self._buffer = bytearray()
        self.crc_errors = 0
        self.length_errors = 0
        self.skipped_bytes = 0

    def push(self, data: bytes) -> Iterator[Frame]:
        self._buffer += data
        while True:
            start = self._buffer.find(SYNC)
            if start < 0:
                keep = 1 if self._buffer.endswith(SYNC[:1]) else 0
                self.skipped_bytes += len(self._buffer) - keep
                del self._buffer[: len(self._buffer) - keep]
                return
            if start:
                self.skipped_bytes += start
                del self._buffer[:start]
            if len(self._buffer) < 6:
                return
            kind, seq, length = struct.unpack_from("<BBH", self._buffer, 2)
            if length > MAX_PAYLOAD:
                self.length_errors += 1
                del self._buffer[:1]
                continue
            total = 6 + length + 2
            if len(self._buffer) < total:
                return
            body = bytes(self._buffer[2 : 6 + length])
            (received,) = struct.unpack_from("<H", self._buffer, 6 + length)
            if received != crc16(body):
                self.crc_errors += 1
                del self._buffer[:1]
                continue
            payload = bytes(self._buffer[6 : 6 + length])
            del self._buffer[:total]
            yield Frame(kind, seq, payload)


def pcm_from_float(block: ArrayLike) -> bytes:
    data = np.asarray(block, dtype=np.float64)
    pcm = np.clip(np.round(data * PCM_SCALE), -32768, 32767).astype("<i2")
    return pcm.tobytes()


def float_from_pcm(payload: bytes) -> FloatArray:
    return np.asarray(np.frombuffer(payload, dtype="<i2").astype(np.float64) / PCM_SCALE)


@dataclass(frozen=True)
class AudioReply:
    seq: int
    compute_us: int
    status: int
    samples: FloatArray


def decode_audio_reply(frame: Frame) -> AudioReply:
    if frame.kind != TYPE_AUDIO_OUT or len(frame.payload) != 4 + 2 * BLOCK:
        raise ValueError("not an audio reply")
    compute_us, status = struct.unpack_from("<HH", frame.payload, 0)
    return AudioReply(frame.seq, compute_us, status, float_from_pcm(frame.payload[4:]))


@dataclass(frozen=True)
class Hello:
    version: int
    fs: int
    block: int
    delay: int
    name: str


def decode_hello(frame: Frame) -> Hello:
    if frame.kind != TYPE_HELLO_REPLY or len(frame.payload) < 9:
        raise ValueError("not a hello reply")
    version, fs, block, delay = struct.unpack_from("<BHHH", frame.payload, 0)
    return Hello(version, fs, block, delay, frame.payload[7:].decode("ascii", errors="replace"))


# --------------------------------------------------------------------- PC rig
def compiler() -> str | None:
    return shutil.which("g++") or shutil.which("c++")


def build_host(
    out_dir: Path, source_dir: Path = HOST_DIR, flags: tuple[str, ...] = ("-O2",)
) -> Path:
    """Compile the firmware sources and the PC front end into one executable."""
    cxx = compiler()
    if cxx is None:
        raise FileNotFoundError(
            "no C++ compiler found; install one with: sudo apt install build-essential"
        )
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / "hushwave_host"
    command = [
        cxx,
        "-std=c++11",
        "-Wall",
        "-Wextra",
        "-Werror",
        *flags,
        f"-I{FIRMWARE_DIR}",
        str(source_dir / "host_main.cpp"),
        *[str(FIRMWARE_DIR / name) for name in SOURCES],
        "-o",
        str(target),
    ]
    run = subprocess.run(command, capture_output=True, text=True, check=False)
    if run.returncode != 0:
        raise RuntimeError(f"firmware build failed:\n{run.stderr}")
    return target


class HostDevice:
    """The firmware compiled for the PC, driven through pipes like a serial port."""

    def __init__(self, executable: Path) -> None:
        self._process = subprocess.Popen(
            [str(executable)], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE
        )
        self.parser = FrameParser()
        self._seq = 0

    def __enter__(self) -> HostDevice:
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        self.close()

    def close(self) -> None:
        if self._process.poll() is None:
            assert self._process.stdin is not None
            self._process.stdin.close()
            self._process.wait(timeout=10)
        for stream in (self._process.stdout, self._process.stderr):
            if stream is not None:
                stream.close()

    def write(self, data: bytes) -> None:
        assert self._process.stdin is not None
        self._process.stdin.write(data)
        self._process.stdin.flush()

    def read_frames(self, count: int) -> list[Frame]:
        assert self._process.stdout is not None
        frames: list[Frame] = []
        while len(frames) < count:
            chunk = self._process.stdout.read1(65536)  # type: ignore[attr-defined]
            if not chunk:
                raise EOFError("the firmware process ended before answering")
            frames.extend(self.parser.push(chunk))
        return frames

    def request(self, kind: int, payload: bytes = b"") -> Frame:
        self._seq = (self._seq + 1) & 0xFF
        self.write(encode_frame(kind, self._seq, payload))
        return self.read_frames(1)[0]

    def hello(self) -> Hello:
        return decode_hello(self.request(TYPE_HELLO))

    def reset(self) -> None:
        reply = self.request(TYPE_RESET)
        if reply.kind != TYPE_RESET_ACK:
            raise RuntimeError("no reset acknowledgement")

    def process(self, x: ArrayLike, depth: int = 3) -> tuple[FloatArray, list[int]]:
        """Stream a whole signal (a multiple of BLOCK samples) with `depth` frames in flight."""
        data = np.asarray(x, dtype=np.float64)
        if data.size % BLOCK:
            raise ValueError(f"the signal length must be a multiple of {BLOCK}")
        blocks = data.reshape(-1, BLOCK)
        out: list[FloatArray] = []
        times: list[int] = []
        sent = 0
        received = 0
        while received < len(blocks):
            while sent < len(blocks) and sent - received < depth:
                self._seq = (self._seq + 1) & 0xFF
                self.write(encode_frame(TYPE_AUDIO_IN, self._seq, pcm_from_float(blocks[sent])))
                sent += 1
            for frame in self.read_frames(1):
                reply = decode_audio_reply(frame)
                out.append(reply.samples)
                times.append(reply.compute_us)
                received += 1
        return np.concatenate(out), times


# ------------------------------------------------------------------- the check
def _check_signals(seed: int) -> dict[str, FloatArray]:
    rng = np.random.default_rng(seed)
    n = BLOCK * 750  # 12 s
    t = np.arange(n) / 16_000
    f0 = 120 + 25 * np.sin(2 * np.pi * 0.4 * t)
    phase = 2 * np.pi * np.cumsum(f0) / 16_000
    voiced = sum(np.sin(k * phase) / k**0.9 for k in range(1, 25))
    envelope = np.clip(np.sin(2 * np.pi * 1.6 * t) ** 2 * 1.5 - 0.3, 0, 1)
    envelope = envelope * (np.sin(2 * np.pi * 0.23 * t) > -0.4)
    hum = 0.03 * np.convolve(rng.standard_normal(n), np.ones(8) / 8, "same")
    impulses = np.zeros(n)
    impulses[::4000] = 0.9
    return {
        "voiced bursts in noise": 0.12 * voiced * envelope + hum,
        "silence": np.zeros(n),
        "very quiet noise": 1e-4 * rng.standard_normal(n),
        "full-scale noise": 0.9 * rng.uniform(-1, 1, n),
        "clipped tone": np.clip(3 * np.sin(2 * np.pi * 440 * t), -1, 1),
        "impulses": impulses,
        "level step": np.where(t > 6, 0.3, 0.0) + 0.01 * rng.standard_normal(n),
    }


def check_firmware(executable: Path, seed: int = 11) -> dict[str, object]:
    """Run the firmware on a set of signals and compare it with the Python engine.

    The reference sees the same 16-bit input and its output is saturated at 16 bit like the
    firmware's, so the remaining difference is single against double precision and rounding.
    """
    from hushwave.live import build_engine

    rows = []
    with HostDevice(executable) as device:
        hello = device.hello()
        for name, signal in _check_signals(seed).items():
            device.reset()
            out, times = device.process(signal)
            quantised = np.minimum(
                np.round(np.clip(signal, -1, 1) * PCM_SCALE) / PCM_SCALE, 32767 / PCM_SCALE
            )
            engine = build_engine(load_b5())
            ref = np.concatenate(
                [engine.process(quantised[i : i + BLOCK]) for i in range(0, signal.size, BLOCK)]
            )
            ref = np.clip(ref, -1.0, 32767 / PCM_SCALE)
            diff = out - ref
            energy = float(np.sum(diff**2))
            rows.append(
                {
                    "signal": name,
                    "blocks": int(signal.size // BLOCK),
                    "max_abs_difference": float(np.max(np.abs(diff))),
                    "rms_difference": float(np.sqrt(np.mean(diff**2))),
                    "snr_db": None
                    if energy == 0.0
                    else float(10 * np.log10(np.sum(ref**2) / energy))
                    if np.sum(ref**2) > 0
                    else None,
                    "finite": bool(np.all(np.isfinite(out))),
                }
            )
            del times
    sizes = json.loads(
        subprocess.run(
            [str(executable), "--sizes"], capture_output=True, text=True, check=True
        ).stdout
    )
    block_s = BLOCK / hello.fs
    up, down = 8 + 2 * BLOCK, 8 + 4 + 2 * BLOCK
    return {
        "firmware": hello.name,
        "protocol_version": hello.version,
        "fs": hello.fs,
        "block": hello.block,
        "delay_samples": hello.delay,
        "signals": rows,
        "max_abs_difference": max(float(r["max_abs_difference"]) for r in rows),  # type: ignore[arg-type]
        "pcm_step": 1.0 / PCM_SCALE,
        "engine_bytes": int(sizes["engine_bytes"]),
        "link_bytes": int(sizes["link_bytes"]),
        "uplink_bytes_per_block": up,
        "downlink_bytes_per_block": down,
        "uplink_bytes_per_second": up / block_s,
        "downlink_bytes_per_second": down / block_s,
        "baud": 921_600,
        "baud_bytes_per_second": 921_600 / 10,
    }
